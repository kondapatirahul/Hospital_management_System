    public static Optional<StaffControlRule> find(String id) {
        return RULES.stream().filter(rule -> rule.id().equals(id)).findFirst();
    }

    public static Map<Integer, List<StaffControlRule>> byPriority() {
        Map<Integer, List<StaffControlRule>> grouped = new TreeMap<>(Comparator.reverseOrder());
        for (StaffControlRule rule : RULES) {
            grouped.computeIfAbsent(rule.priority(), ignored -> new ArrayList<>()).add(rule);
        }
        grouped.replaceAll((priority, values) -> List.copyOf(values));
        return Collections.unmodifiableMap(grouped);
    }

    public static List<StaffControlRule> mandatoryControls() {
        return RULES.stream().filter(StaffControlRule::mandatory).toList();
    }

    public static List<StaffControlRule> controlsForPriority(int priority) {
        return RULES.stream().filter(rule -> rule.priority() == priority).toList();
    }

    public static int controlCount() {
        return RULES.size();
    }
