-- CareFlow Phase 4 enterprise operations tables. Review on a staging database before production use.
CREATE TABLE IF NOT EXISTS cf4_revenueplan (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(180) NOT NULL,
  description VARCHAR(4000),
  status VARCHAR(80) NOT NULL,
  reference_code VARCHAR(100),
  owner VARCHAR(160),
  department VARCHAR(160),
  counterparty VARCHAR(160),
  amount DECIMAL(14,2) DEFAULT 0,
  due_date DATE,
  evidence_reference VARCHAR(1000),
  decision_note VARCHAR(1000),
  created_at DATETIME NOT NULL,
  updated_at DATETIME,
  created_by VARCHAR(120),
  updated_by VARCHAR(120),
  version BIGINT,
  INDEX idx_cf4_revenueplan_status(status),
  INDEX idx_cf4_revenueplan_reference(reference_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

